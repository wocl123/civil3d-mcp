import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash, verify } from 'node:crypto';
import { dirname, join } from 'node:path';
import { prepareGitHubRelease } from '../../scripts/github-publish.mjs';
import { trustedReleaseKey } from '../build/update/driveRelease.js';
const exe = process.argv[2], artifactRoot = dirname(exe);
const version = /MyCivil3DMcp-(\d+\.\d+\.\d+)-win-x64\.exe$/.exec(exe)?.[1];
const config = { version, githubRepo: process.env.MY_CIVIL3D_GITHUB_REPO, adminEmail: process.env.MY_CIVIL3D_ADMIN_EMAIL, ingestUrl: process.env.MY_CIVIL3D_INGEST_URL };
assert.ok(version && config.githubRepo && config.ingestUrl);
const prepared = await prepareGitHubRelease(config, artifactRoot);
const key = await trustedReleaseKey();
const envelope = JSON.parse(await readFile(prepared.manifest, 'utf8'));
const payload = Buffer.from(envelope.payload, 'base64');
assert.ok(verify('sha256', payload, key, Buffer.from(envelope.signature, 'base64')));
assert.deepEqual(JSON.parse(payload), prepared.release);
assert.equal(prepared.release.sha256, createHash('sha256').update(await readFile(exe)).digest('hex'));
await assert.rejects(prepareGitHubRelease({ ...config, githubRepo: 'wrong/distribution' }, artifactRoot), /EXE/);
await assert.rejects(prepareGitHubRelease({ ...config, ingestUrl: config.ingestUrl.replace('/exec', '/dev') }, artifactRoot));
await assert.rejects(prepareGitHubRelease({ ...config, adminEmail: 'other@example.com' }, artifactRoot), /EXE/);
assert.equal(await readFile(prepared.manifest, 'utf8'), JSON.stringify(envelope, null, 2));
console.log('github publish ok: actual signed EXE, embedded repo/intake/admin verification, signed metadata and checksum; no remote writes');
