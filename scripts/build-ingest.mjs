// Generate Apps Script validation from the actual server validator.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const ts = require('../server/node_modules/typescript');
const parameters = await readFile(resolve(repo, 'server/src/knowledge/parameters.ts'), 'utf8');
const pureParameters = parameters.slice(parameters.indexOf('export const PARAMETERS'), parameters.indexOf('const localFile'));
const validator = (await readFile(resolve(repo, 'server/src/admin/validate.ts'), 'utf8')).replace(/^import .*;\r?\n/gm, '');
const source = (pureParameters + '\n' + validator).replace(/\bexport\s+/g, '');
const built = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.None } }).outputText;
const dest = resolve(repo, 'scripts/google-ingest');
await mkdir(dest, { recursive: true });
await writeFile(resolve(dest, 'Validation.gs'), '// Generated by scripts/build-ingest.mjs. Do not edit.\n' + built);
console.log('Apps Script 검증 코드 생성 완료');
